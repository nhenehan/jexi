# Grammar tables written as Julia source (rexi-schema-gen). A package that
# includes the generated module gets its `GRAMMARS` constant compiled into the
# package image, so loading the tables costs nothing at run time.

"""
    SchemaGen

Writes grammar tables as Julia source:

```julia
JExi.SchemaGen.generate(["a.xsd", "b.xsd"]; out = "src/tables.jl", module_name = "Tables")
```

The file holds `module Tables`, with `const GRAMMARS = ...` and one
`const LN_<NAME> = QNameId(uri, local)` per element and attribute name, for
the `start_element!(enc, ::QNameId)` and `attribute!(enc, ::QNameId, v)` entry
points.
"""
module SchemaGen

import ..JExi as J

"""
    screaming_snake(s) -> String

A constant name from a local name: `orderId` -> `ORDER_ID`. Anything that is
not an ASCII letter or digit becomes `_`; a leading digit gets a `_` before it.
"""
function screaming_snake(s::AbstractString)
    io = IOBuffer()
    prev_lower = false
    last = '\0'
    for c in s
        if isascii(c) && (isletter(c) || isdigit(c))
            if isuppercase(c) && prev_lower
                print(io, '_')
            end
            prev_lower = islowercase(c) || isdigit(c)
            last = uppercase(c)
            print(io, last)
        else
            last == '_' || (print(io, '_'); last = '_')
            prev_lower = false
        end
    end
    out = String(take!(io))
    (isempty(out) || isdigit(out[1])) && (out = "_" * out)
    return out
end

idx(i::Integer) = i == J.NONE ? "J.NONE" : string(Int(i))
span(s::J.Span) = "J.Span($(s.start), $(s.len))"
qn(q::J.QNameId) = "J.QNameId($(idx(q.uri)), $(idx(q.local_name)))"
term(t::J.Terminal) = "J.Terminal(J.$(t.kind), $(t.a), $(t.b), $(t.c))"

function kind(k::J.DatatypeKind)
    t = k.tag
    t == J.K_STRING && return "J.string_kind(J.$(k.whitespace))"
    t == J.K_RESTRICTED_STRING && return J.has_alphabet(k) ?
        "J.restricted_string_kind(J.$(k.whitespace), $(Int(k.set)))" : "J.restricted_string_kind(J.$(k.whitespace))"
    t == J.K_NBIT && return "J.nbit_kind($(k.min), $(Int(k.bits)))"
    t == J.K_DATETIME && return "J.datetime_kind(J.$(k.datetime))"
    t == J.K_ENUMERATION && return "J.enum_kind($(idx(k.set)), $(idx(k.item)))"
    t == J.K_LIST && return "J.list_kind($(idx(k.item)))"
    return "J.DatatypeKind(J.$t)"
end

function vector_lines(io::IO, T::AbstractString, items, render)
    if isempty(items)
        println(io, "    $T[],")
        return
    end
    println(io, "    $T[")
    for x in items
        println(io, "        ", render(x), ",")
    end
    println(io, "    ],")
end

function id_lines(io::IO, v::Vector{UInt32})
    if isempty(v)
        println(io, "    J.StrIdx[],")
        return
    end
    println(io, "    J.StrIdx[")
    for chunk in Iterators.partition(v, 16)
        println(io, "        ", join(idx.(chunk), ", "), ",")
    end
    println(io, "    ],")
end

"""The `LN_*` constants: one per element or attribute name in the tables."""
function name_consts(io::IO, g::J.GrammarSet)
    qnames = Set{J.QNameId}()
    foreach(e -> push!(qnames, e.qname), g.elements)
    for p in g.productions
        p.terminal.kind == J.T_AT && push!(qnames, J.term_qname(p.terminal))
    end
    used = Set{String}()
    for q in sort!(collect(qnames))
        l = J.local_name_str(g, q)
        l === nothing && continue
        ident = "LN_" * screaming_snake(l)
        if ident in used
            ident = "$(ident)_$(q.uri)_$(q.local_name)"
        end
        push!(used, ident)
        u = something(J.uri_str(g, q.uri), "")
        println(io, "\"\"\"`{$(escape_doc(u))}$(escape_doc(l))`\"\"\"")
        println(io, "const $ident = $(qn(q))")
    end
    isempty(qnames) || println(io)
end

escape_doc(s::AbstractString) = replace(s, "\\" => "\\\\", "\"" => "\\\"", "\$" => "\\\$")

"""
    render(g; name = "GRAMMARS", module_name = "Grammars", source = "") -> String

The Julia source of a module that defines `g` as the constant `name`.
"""
function render(g::J.GrammarSet; name::AbstractString = "GRAMMARS", module_name::AbstractString = "Grammars",
    source::AbstractString = "")
    io = IOBuffer()
    println(io, "# @generated by JExi.SchemaGen. Do not edit by hand.")
    isempty(source) || println(io, "# Source: ", source)
    println(io)
    println(io, "module ", module_name)
    println(io)
    println(io, "import JExi as J")
    println(io)
    name_consts(io, g)
    println(io, "const ", name, " = J.GrammarSet(")
    vector_lines(io, "String", g.strings, repr)
    vector_lines(io, "J.UriEntry", g.uris, u -> "J.UriEntry($(u.uri), $(span(u.prefixes)), $(span(u.local_names)))")
    id_lines(io, g.prefixes)
    id_lines(io, g.local_names)
    vector_lines(io, "J.Production", g.productions, p -> "J.Production($(term(p.terminal)), $(idx(p.next)))")
    vector_lines(io, "J.Rule", g.rules, r -> "J.Rule($(span(r.productions)))")
    vector_lines(io, "J.Grammar", g.grammars, x -> "J.Grammar($(span(x.rules)))")
    vector_lines(io, "J.ElementDecl", g.elements,
        e -> "J.ElementDecl($(qn(e.qname)), $(idx(e.type_idx)), $(e.nillable), $(e.is_global))")
    id_lines(io, g.global_elements)
    vector_lines(io, "J.GlobalAttribute", g.global_attributes, a -> "J.GlobalAttribute($(qn(a.qname)), $(idx(a.type_idx)))")
    vector_lines(io, "J.TypeDecl", g.types,
        t -> "J.TypeDecl($(qn(t.qname)), $(idx(t.grammar)), $(idx(t.empty_grammar)), $(kind(t.datatype)), $(t.has_datatype), $(t.typecastable))")
    vector_lines(io, "J.Span", g.enum_sets, span)
    id_lines(io, g.enum_values)
    println(io, "    ", g.schema_id === nothing ? "nothing" : repr(g.schema_id), ",")
    println(io, ")")
    println(io)
    println(io, "end # module ", module_name)
    return String(take!(io))
end

"""
    generate(xsds; out, name = "GRAMMARS", module_name = "Grammars", check = false) -> Bool

Compiles the schemas and writes the module to `out`. With `check = true`,
nothing is written: it returns whether `out` already holds exactly that source.
"""
function generate(xsds::AbstractVector{<:AbstractString}; out::AbstractString, name::AbstractString = "GRAMMARS",
    module_name::AbstractString = "Grammars", check::Bool = false)
    g = J.compile_files(xsds...)
    text = render(g; name, module_name, source = join(basename.(xsds), ", "))
    if check
        return isfile(out) && read(out, String) == text
    end
    mkpath(dirname(abspath(out)))
    write(out, text)
    return true
end

end # module SchemaGen
